#!/usr/bin/env python3
"""Generate a C++ header holding the flasher stub binary for the EasyPCR bootloader.

Reads the stub ELF directly (no esptool dependency) and emits the .text/.data
segments plus the load addresses the STM32 side needs for MEM_BEGIN/MEM_END.

Usage: gen_stub_hpp.py <stub.elf> <output.hpp> <namespace> <chip-name>
"""

import struct
import sys

ELFCLASS32 = 1
SHT_NOBITS = 8


class Elf32:
    def __init__(self, path):
        with open(path, "rb") as f:
            self.data = f.read()

        if self.data[:4] != b"\x7fELF" or self.data[4] != ELFCLASS32:
            raise ValueError("%s is not a 32-bit ELF file" % path)
        if self.data[5] != 1:
            raise ValueError("%s is not little-endian" % path)

        (self.entry, _phoff, shoff, _flags, _ehsize, _phentsize, _phnum,
         shentsize, shnum, shstrndx) = struct.unpack_from("<IIIIHHHHHH", self.data, 24)

        self.sections = {}
        raw = []
        for i in range(shnum):
            off = shoff + i * shentsize
            name, sh_type, _flags, addr, offset, size = struct.unpack_from("<IIIIII", self.data, off)
            raw.append((name, sh_type, addr, offset, size))

        strtab_off = raw[shstrndx][3]
        for name_off, sh_type, addr, offset, size in raw:
            end = self.data.index(b"\0", strtab_off + name_off)
            name = self.data[strtab_off + name_off:end].decode("ascii")
            payload = b"" if sh_type == SHT_NOBITS else self.data[offset:offset + size]
            self.sections[name] = (addr, payload)

    def section(self, name):
        if name not in self.sections:
            raise ValueError("section %s not found" % name)
        return self.sections[name]


def hex_rows(blob):
    out = ""
    for i in range(0, len(blob), 16):
        out += "    " + ", ".join("0x{:02X}".format(b) for b in blob[i:i + 16]) + ",\n"
    return out


def main():
    if len(sys.argv) != 5:
        print(__doc__)
        sys.exit(1)

    elf_path, out_path, namespace, chip = sys.argv[1:5]

    elf = Elf32(elf_path)
    text_start, text = elf.section(".text")
    data_start, data = elf.section(".data")
    bss_start, _ = elf.section(".bss")

    # Pad text to a multiple of 4, the ROM loader writes words.
    if len(text) % 4:
        text += b"\0" * (4 - len(text) % 4)

    h = "// %s Stub Flasher Binary Data (with hardware SHA256 support)\n" % chip
    h += "// Generated by esptool-legacy-flasher-stub/flasher_stub/gen_stub_hpp.py\n"
    h += "// Do not edit by hand - regenerate with `make %s-hpp`.\n\n" % namespace.replace("_stub", "")
    h += "#pragma once\n#include <cstdint>\n\nnamespace %s {\n\n" % namespace
    h += "constexpr uint32_t STUB_ENTRY = 0x{:08X};\n".format(elf.entry)
    h += "constexpr uint32_t STUB_TEXT_START = 0x{:08X};\n".format(text_start)
    h += "constexpr uint32_t STUB_DATA_START = 0x{:08X};\n".format(data_start)
    h += "constexpr uint32_t STUB_BSS_START = 0x{:08X};\n\n".format(bss_start)
    h += "constexpr size_t STUB_TEXT_SIZE = {};\n".format(len(text))
    h += "constexpr size_t STUB_DATA_SIZE = {};\n\n".format(len(data))
    h += "alignas(4) constexpr uint8_t STUB_TEXT[STUB_TEXT_SIZE] = {\n"
    h += hex_rows(text)
    h += "};\n\nalignas(4) constexpr uint8_t STUB_DATA[STUB_DATA_SIZE] = {\n"
    h += hex_rows(data)
    h += "};\n\n} // namespace %s\n" % namespace

    with open(out_path, "w") as f:
        f.write(h)

    print("  Generated %s (%d text @ 0x%08X, %d data @ 0x%08X, entry 0x%08X)"
          % (out_path, len(text), text_start, len(data), data_start, elf.entry))


if __name__ == "__main__":
    main()
